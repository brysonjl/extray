// Display caps. The TRUE site count is preserved on the row (`total_usage`) so
// renderers compute an honest "+N more" and the synthesis digest reports the
// real call-site count, not the capped one.
const MAX_USAGE_SITES = 8;
const MAX_EXAMPLE_SITES = 3;

/** A match pattern is not an API permission (MV2-style host entries in `permissions`). */
function isHostPattern(p: string): boolean {
  return p.includes("://") || p.startsWith("<") || p.startsWith("*");
}

/**
 * The pipeline's destination extraction occasionally lifts string fragments out
 * of non-URL literals (e.g. the Netscape cookie-file template's "# This file
 * was generated by ExtRay Demo Cookie Manager" comment) and records them as "hosts". Filter
 * the destinations table to values that actually look like a host: a
 * dotted domain, an IPv4 (optionally :port), or localhost(:port) — never
 * something containing whitespace or a `:` that is not a port. A real host the
 * filter would wrongly drop is far less harmful than a table full of comment
 * noise that makes every report look broken.
 */
export function looksLikeHost(host: string): boolean {
  const h = host.trim();
  if (h === "" || /\s/.test(h)) return false;
  if (/^localhost(:\d{1,5})?$/i.test(h)) return true;
  if (/^\d{1,3}(\.\d{1,3}){3}(:\d{1,5})?$/.test(h)) return true; // IPv4 (+ port)
  // dotted hostname with a 2+ char alpha TLD, optional :port; templated hosts
  // keep their `*` wildcard from layer 4.
  return /^[a-z0-9*]([a-z0-9*-]*\.)+[a-z]{2,}(:\d{1,5})?$/i.test(h);
}

export function buildIdentity(pack: EvidencePack, storeId: string | null): ExtensionIdentity {
  const m = pack.extension.manifest;
  return {
    name: typeof m.name === "string" ? m.name : null,
    version: typeof m.version === "string" ? m.version : null,
    manifest_version: pack.manifest_analysis.manifest_version,
    store_id: pack.fixture ? null : storeId,
    ...(pack.fixture ? { fixture: pack.fixture } : {}),
  };
}

export function buildPermissions(pack: EvidencePack): PermissionsSection {
  const m = pack.extension.manifest;
  const declared = (Array.isArray(m.permissions) ? m.permissions : [])
    .filter((p): p is string => typeof p === "string")
    .filter((p) => !isHostPattern(p));
  const optional = (Array.isArray(m.optional_permissions) ? m.optional_permissions : [])
    .filter((p): p is string => typeof p === "string")
    .filter((p) => !isHostPattern(p));
  const usage = pack.cross_file.permission_usage;
  const unused = new Set(pack.cross_file.unused_permissions);

  const row = (permission: string, isOptional: boolean): PermissionRow => {
    const sites = usage[permission] ?? [];
    // Layer 4 buckets every declared permission into exactly one of
    // permission_usage / unused_permissions / cannot_determine_statically, so
    // "undetermined" is the correct default for anything not proven used or
    // unused — including older/hand-built packs that omit
    // cannot_determine_statically entirely.
    const status: PermissionRow["status"] =
      sites.length > 0 ? "used" : unused.has(permission) ? "unused" : "undetermined";
    const info = describePermission(permission);
    const base: PermissionRow = {
      permission,
      optional: isOptional,
      status,
      usage: sites.slice(0, MAX_USAGE_SITES),
      total_usage: sites.length,
      description: info.summary,
      doc_url: info.doc_url,
      install_warning: info.install_warning,
      usage_plain: "", // filled below once the row is shaped (describeUsage reads it)
    };
    base.usage_plain = describeUsage(base);
    return base;
  };

  const hosts = pack.manifest_analysis.host_permissions ?? { required: [], optional: [] };
  return {
    api: [...declared.map((p) => row(p, false)), ...optional.filter((p) => !declared.includes(p)).map((p) => row(p, true))],
    hosts,
    hosts_plain: describeHosts(hosts),
    dangerous_combinations: pack.manifest_analysis.dangerous_combinations,
  };
}

/**
 * Report-shaped enrichment for one host: the COMPLETE artifact facts plus the
 * three descriptive derived booleans. The derived signals reuse the same
 * deriveSignals() the LLM projection uses, so the report and the pack view can
 * never disagree about whether a host is newly-registered/expired/high-risk.
 */
function toDestinationEnrichment(record: HostEnrichmentRecord, analyzedAt: string): DestinationEnrichment {
  const signals = deriveSignals(record, analyzedAt);
  return {
    kind: record.kind,
    lookup_status: record.lookup_status,
    domain: record.domain,
    ip: record.ip,
    dns_status: record.dns_status,
    resolved_addresses: record.resolved_addresses,
    cname_chain: record.cname_chain,
    cdn: record.cdn,
    newly_registered: signals.newly_registered,
    high_risk_country: signals.high_risk_country,
    expired_or_hold: signals.expired_or_hold,
  };
}

export function buildDestinations(pack: EvidencePack, enrichment?: HostEnrichment | null): DestinationsSection {
  // Example call sites per host, joined from the per-script destination lists.
  // Keyed with layer 4's exact host normalization (destinationHostOf) so the
  // join against destination_summary never misses on ports/IPv6/templates.
  const examples = new Map<string, DestinationRow["example_sites"]>();
  for (const script of pack.scripts) {
    for (const d of script.network_destinations as NetworkDestination[]) {
      const host = destinationHostOf(d.value);
      if (!host) continue;
      const list = examples.get(host) ?? [];
      if (list.length < MAX_EXAMPLE_SITES) {
        list.push({ path: script.path, line: d.location.line, role: d.ast_role });
        examples.set(host, list);
      }
    }
  }

  // Party adjudication per host from the data-flow join (improvement 012).
  // When flows disagree, report the strongest claim the pipeline made:
  // first-party-extension > external > unknown.
  const party = new Map<string, DestinationRow["party"]>();
  const rank = { "first-party-extension": 2, external: 1, unknown: 0 } as const;
  for (const flow of pack.cross_file.data_flows ?? []) {
    if (!flow.dest_host) continue;
    const prev = party.get(flow.dest_host);
    if (prev == null || rank[flow.dest_party] > rank[prev as keyof typeof rank]) {
      party.set(flow.dest_host, flow.dest_party);
    }
  }

  // RDAP enrichment join (improvement 015), keyed by the SAME host string layer 4
  // produced. A missing record means "never enriched" → enrichment null, never a
  // fabricated clean signal. Descriptive only; verdict.ts never reads it.
  const byHost = recordsByHost(enrichment);

  const rows: DestinationRow[] = pack.cross_file.destination_summary
    .filter((d) => looksLikeHost(d.host))
    .map((d) => {
      const record = byHost.get(d.host);
      return {
        host: d.host,
        references: d.references,
        any_dynamic: d.any_dynamic,
        reached_via: d.reached_via,
        example_sites: examples.get(d.host) ?? [],
        party: party.get(d.host) ?? null,
        enrichment: record ? toDestinationEnrichment(record, pack.analyzed_at) : null,
      };
    });
  rows.sort((a, b) => b.references - a.references || a.host.localeCompare(b.host));

  return { rows, unresolved: pack.external_call_ledger.unresolved_destinations };
}

export function buildObfuscation(pack: EvidencePack): ObfuscationSection {
  const flagged = pack.scripts
    .filter((s) => s.obfuscation?.flagged)
    .map((s) => ({
      path: s.path,
      identifier_entropy: s.obfuscation!.identifier_entropy,
      mean_identifier_length: s.obfuscation!.mean_identifier_length,
      hex_escape_density_per_kb: s.obfuscation!.hex_escape_density_per_kb,
      string_array_decoder_detected: s.obfuscation!.string_array_decoder_detected,
      packer_signature: s.obfuscation!.packer_signature,
    }));
  return { flagged, opaque_regions: pack.external_call_ledger.opaque_regions };
}

/**
 * The store-listing artifact's relevant slice (008b). Structurally mirrors
 * src/listing/types.ts DeveloperListing — typed locally so the report layer
 * has no import dependency on the fetcher.
 */
export interface ListingInput {
  fetched_at: string;
  source: "chrome-web-store" | "unavailable";
  developer: {
    name: string | null;
    address: string | null;
    email: string | null;
    website: string | null;
    is_trader: boolean | null;
  };
  description: string | null;
  country: string | null;
}

export function buildDeveloper(
  dev: Developer,
  listing: ListingInput | null | undefined,
  highRiskCountry: boolean | null,
): DeveloperSection {
  const fromListing = listing && listing.source === "chrome-web-store" ? listing : null;
  const sources: DeveloperSection["sources"] = ["manifest"];
  if (fromListing) sources.push("store_listing");
  return {
    name: fromListing?.developer.name ?? dev.author?.name ?? null,
    email: fromListing?.developer.email ?? dev.author?.email ?? null,
    website: fromListing?.developer.website ?? dev.homepage_url,
    address: fromListing?.developer.address ?? dev.address,
    country: fromListing?.country ?? dev.country,
    is_trader: fromListing?.developer.is_trader ?? null,
    high_risk_country: highRiskCountry,
    update_url: dev.update_url,
    non_store_update_url: dev.non_store_update_url,
    sources,
    listing_available: listing ? listing.source === "chrome-web-store" : null,
    listing_fetched_at: listing?.fetched_at ?? null,
  };
}

export function buildCoverage(pack: EvidencePack): CoverageSection {
  const ledger = pack.external_call_ledger;
  return {
    opaque_regions: ledger.counts.opaque_regions,
    indirect_calls: ledger.counts.indirect_calls,
    unresolved_destinations: ledger.counts.unresolved_destinations,
    unparsed_files: ledger.unparsed_files,
    structural_limits: STRUCTURAL_LIMITS,
  };
}
