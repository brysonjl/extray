// Deterministic section builders: evidence pack → the report's guaranteed
// sections. No LLM text enters here — these sections render identically for
// the same pack bytes, which is what makes the report skeleton consistent
// across runs, models, and extensions. The data was always collected (layer 4's
// permission_usage, layer 3's destinations, the soundness ledger); this module
// is the missing surfacing step.

