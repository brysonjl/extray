#!/usr/bin/env -S npx tsx
// Export the product-visible slice of the bake-off DB as a D1-importable SQL
// file. D1 is SQLite, but `wrangler d1 execute
// --file` rejects PRAGMA/BEGIN/COMMIT and caps a single statement at ~100KB —
// and risk_report_json blobs run up to ~1MB. So: schema DDL from
// src/db/schema.ts, multi-row INSERT batches for ordinary rows, and oversized
// TEXT values split into an INSERT plus appending UPDATE statements.
//
// Product tables: schema_meta, run, target, report, finding, and per-pass usage.
// Eval-only tables (scorecard, sample_score) and never-read heavy columns
// (report_text, structured_json, run.raw_json, run.cost_rates_json) stay
// local. `submission` ships as schema only — the deployed queue starts empty.
//
// Re-import upserts stable row IDs and prunes only rows absent from the new
// manifest. Retained submission.result_report_id links survive refresh; removed
// or withheld reports clear their references through ON DELETE SET NULL.
//
// Store-backed targets whose declared locales exclude English are dropped from
// the export (see scripts/_locale-filter.ts) — the local bake-off DB is
// untouched, only the product-visible slice that ships to D1 is filtered.
// Runs with a canonical_hold ledger event and all their dependent rows are
// also excluded, including from direct report access after import.
//
//   npm run explorer:d1:export -- [--db .out/bakeoff.sqlite] [--out .out/d1-export.sql]
//   npx wrangler d1 execute ext-ray --local  --file=.out/d1-export.sql
//   npx wrangler d1 execute ext-ray --remote --file=.out/d1-export.sql

import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { SCHEMA_SQL } from "../src/db/schema.ts";
import { ELIGIBLE_RUN_SQL } from "../src/product/eligibility.ts";
import { isEnglishOk } from "./_locale-filter.ts";

/** Keep every emitted statement comfortably under D1's ~100KB cap: raw chunk
 *  ≤ 30K chars ≤ ~60KB escaped worst-case, plus statement scaffolding. */
const MAX_VALUE_INLINE = 30_000;
const MAX_STATEMENT_CHARS = 70_000;

// Data columns per table; '*' = all. report/run drop the never-read blobs.
const TABLES: { name: string; exclude: string[] }[] = [
  { name: "schema_meta", exclude: [] },
  { name: "run", exclude: ["raw_json", "cost_rates_json"] },
  { name: "target", exclude: [] },
  { name: "report", exclude: ["report_text", "structured_json"] },
  { name: "finding", exclude: [] },
  { name: "usage", exclude: [] },
];

interface Args {
  db: string;
  out: string;
}

function parseArgs(argv: string[]): Args {
  const out: Args = { db: ".out/bakeoff.sqlite", out: ".out/d1-export.sql" };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--db") out.db = argv[++i] ?? out.db;
    else if (a === "--out") out.out = argv[++i] ?? out.out;
  }
  return out;
}

function sqlLiteral(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "bigint") return String(v);
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString("hex")}'`;
  return `'${String(v).replaceAll("'", "''")}'`;
}

/** Split on code-point boundaries: never cut a surrogate pair, or the file
 *  would carry lone surrogates and the reimported text would not round-trip. */
function chunkText(s: string, size: number): string[] {
  const chunks: string[] = [];
  let i = 0;
  while (i < s.length) {
    let end = Math.min(i + size, s.length);
    const cu = s.charCodeAt(end - 1);
    if (cu >= 0xd800 && cu <= 0xdbff && end < s.length) end++;
    chunks.push(s.slice(i, end));
    i = end;
  }
  return chunks;
}

// ---- pure filtering (unit-tested) -------------------------------------------

export interface TargetRef {
  id: number;
  storeId: string;
}

/** target.id values to drop from the export: store-backed targets whose
 *  declared locales exclude English. `languagesOk` is injected so the pure
 *  decision (which ids to drop) is testable without touching the filesystem. */
export function nonEnglishTargetIds(targets: TargetRef[], languagesOk: (storeId: string) => boolean): Set<number> {
  const out = new Set<number>();
  for (const t of targets) {
    if (!languagesOk(t.storeId)) out.add(t.id);
  }
  return out;
}

/** Read-only snapshot construction; held runs and their dependent rows never
 * ship. Eligible per-pass usage ships with reports; scorecard/ledger data stay local. */
export function buildD1Export(
  db: DatabaseSync,
  languagesOk: (storeId: string) => boolean = isEnglishOk,
): { sql: string; counts: Record<string, number> } {
  const lines: string[] = [
    "-- Generated by scripts/export-d1.ts — product-visible slice of the bake-off DB.",
    "-- Import: npx wrangler d1 execute <db> [--local|--remote] --file=<this file>",
    SCHEMA_SQL.trim(),
  ];
  const counts: Record<string, number> = {};

  // Store-backed targets whose declared locales exclude English never ship to
  // D1 — dropped here (target), cascaded manually to report/finding (below)
  // since this is a plain SELECT export, not a real FK-cascading DELETE.
  const storeTargets = db
    .prepare("SELECT id, store_id AS storeId FROM target WHERE store_id IS NOT NULL")
    .all() as unknown as TargetRef[];
  const excludedTargetIds = nonEnglishTargetIds(storeTargets, languagesOk);
  let excludedReportIds = new Set<number>();
  if (excludedTargetIds.size > 0) {
    const marks = [...excludedTargetIds].join(",");
    const reportRows = db.prepare(`SELECT id FROM report WHERE target_id IN (${marks})`).all() as { id: number }[];
    excludedReportIds = new Set(reportRows.map((r) => r.id));
  }
  const whereClauses: Record<string, string> = {};
  if (excludedTargetIds.size > 0) whereClauses.target = `id NOT IN (${[...excludedTargetIds].join(",")})`;
  if (excludedReportIds.size > 0) {
    whereClauses.report = `id NOT IN (${[...excludedReportIds].join(",")})`;
    whereClauses.finding = `report_id NOT IN (${[...excludedReportIds].join(",")})`;
  }

  const eligibleRunIds = `SELECT r.id FROM run r WHERE ${ELIGIBLE_RUN_SQL}`;
  whereClauses.run = `id IN (${eligibleRunIds})`;
  whereClauses.target = [whereClauses.target, `run_id IN (${eligibleRunIds})`].filter(Boolean).join(" AND ");
  whereClauses.report = [
    whereClauses.report,
    `run_id IN (${eligibleRunIds})`,
    `target_id IN (SELECT id FROM target WHERE ${whereClauses.target})`,
  ].filter(Boolean).join(" AND ");
  whereClauses.finding = `report_id IN (SELECT id FROM report WHERE ${whereClauses.report})`;

  whereClauses.usage = `run_id IN (${eligibleRunIds}) AND (target_id IS NULL OR target_id IN (SELECT id FROM target WHERE ${whereClauses.target}))`;
  // Upsert stable IDs. Deleting reports before import would erase exact job
  // result references through ON DELETE SET NULL, even for retained reports.
  // A manifest prunes only genuinely removed/withheld rows after the import.
  lines.push("CREATE TABLE IF NOT EXISTS export_manifest(table_name TEXT NOT NULL,row_id INTEGER NOT NULL,PRIMARY KEY(table_name,row_id));");
  lines.push("DELETE FROM export_manifest;");

  for (const { name, exclude } of TABLES) {
    const cols = (db.prepare(`PRAGMA table_info(${name})`).all() as { name: string }[])
      .map((c) => c.name)
      .filter((c) => !exclude.includes(c));
    const where = whereClauses[name] ? ` WHERE ${whereClauses[name]}` : "";
    const rows = db.prepare(`SELECT ${cols.join(", ")} FROM ${name}${where}`).all() as Record<string, unknown>[];
    counts[name] = rows.length;

    const primary = name === "schema_meta" ? "key" : "id";
    const upsert = ` ON CONFLICT(${primary}) DO UPDATE SET ${cols.filter(c => c !== primary).map(c => `${c}=excluded.${c}`).join(",")}`;
    const insertHead = `INSERT INTO ${name} (${cols.join(", ")}) VALUES`;
    if (primary === "id") {
      for (let i=0; i<rows.length; i+=500) lines.push(`INSERT INTO export_manifest(table_name,row_id) VALUES ${rows.slice(i,i+500).map(r => `('${name}',${sqlLiteral(r.id)})`).join(",")};`);
    }
    let batch: string[] = [];
    let batchChars = insertHead.length;
    const flush = (): void => {
      if (batch.length > 0) lines.push(`${insertHead}\n${batch.join(",\n")}${upsert};`);
      batch = [];
      batchChars = insertHead.length;
    };

    for (const row of rows) {
      // Oversized TEXT values get their own INSERT + appending UPDATEs.
      const oversized = cols.filter((c) => typeof row[c] === "string" && (row[c] as string).length > MAX_VALUE_INLINE);
      if (oversized.length > 0) {
        flush();
        const tuple = cols.map((c) => (oversized.includes(c) ? "''" : sqlLiteral(row[c]))).join(", ");
        lines.push(`${insertHead} (${tuple})${upsert};`);
        for (const c of oversized) {
          for (const chunk of chunkText(row[c] as string, MAX_VALUE_INLINE)) {
            lines.push(
              `UPDATE ${name} SET ${c} = ${c} || ${sqlLiteral(chunk)} WHERE id = ${sqlLiteral(row.id)};`,
            );
          }
        }
        continue;
      }
      const tuple = `(${cols.map((c) => sqlLiteral(row[c])).join(", ")})`;
      if (batchChars + tuple.length > MAX_STATEMENT_CHARS) flush();
      batch.push(tuple);
      batchChars += tuple.length + 2;
    }
    flush();
  }

  for (const {name} of [...TABLES].reverse()) {
    if (name !== "schema_meta") lines.push(`DELETE FROM ${name} WHERE id NOT IN (SELECT row_id FROM export_manifest WHERE table_name='${name}');`);
  }
  lines.push("DELETE FROM export_manifest;");
  const sql = `${lines.join("\n")}\n`;
  return { sql, counts };
}

/** A live analyzer can commit while exporting; every table must describe the
 * same read snapshot so references and the prune manifest agree. */
export function buildConsistentD1Export(db: DatabaseSync, languagesOk: (storeId: string) => boolean = isEnglishOk): ReturnType<typeof buildD1Export> {
  db.exec("BEGIN");
  try { const result = buildD1Export(db, languagesOk); db.exec("COMMIT"); return result; }
  catch (error) { db.exec("ROLLBACK"); throw error; }
}

function main(): void {
  const args = parseArgs(process.argv.slice(2));
  const db = new DatabaseSync(args.db, { readOnly: true });
  let result: ReturnType<typeof buildD1Export>;
  try { result = buildConsistentD1Export(db); } finally { db.close(); }
  const { sql, counts } = result;
  writeFileSync(args.out, sql);
  const summary = TABLES.map((t) => `${t.name}=${counts[t.name]}`).join(" ");
  console.log(`Wrote ${args.out} (${(sql.length / 1024 / 1024).toFixed(1)}MB): ${summary}`);
}

// Entry-guarded so test imports of the pure helpers don't run the export
// (CI has no .out/bakeoff.sqlite).
if (import.meta.url === `file://${process.argv[1]}`) main();
