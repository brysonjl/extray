// Build the portable copies without introducing a runtime dependency on Markdown.
// Pi consumes guidance.ts; installed skills consume the generated reference.
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DIMENSIONS, DIMENSION_BRIEF, REMOTE_CODE_RULES, HOST_RESOLUTION_RULE } from "../src/methodologies/pi/guidance.ts";
import { CLAIM_TYPES, CATEGORIES, CONFIDENCES, FINDING_TYPES, SEVERITIES } from "../src/methodologies/findings.ts";

const root = new URL("../skills/extray-review/references/", import.meta.url);
const text = { type: "string", minLength: 1 };
const nullableText = { type: ["string", "null"], minLength: 1 };
const strings = { type: "array", items: text };
const enumOf = (values: readonly string[]) => ({ type: "string", enum: values });
const object = (properties: Record<string, unknown>, required = Object.keys(properties)) => ({
  type: "object", additionalProperties: false, required, properties,
});
const location = {
  ...object({ line: { type: "integer", minimum: 1 }, column: { type: "integer", minimum: 1 } }, ["line"]),
  type: ["object", "null"],
};

export function skillAssets(): Record<string, string> {
  const finding = object({
    id: text, title: text, claim_type: enumOf(CLAIM_TYPES),
    severity: enumOf(SEVERITIES), category: enumOf(CATEGORIES),
    confidence: enumOf(CONFIDENCES), finding_type: enumOf(FINDING_TYPES),
    claimed_mechanism: { type: "string" },
    evidence_refs: { type: "array", minItems: 1, items: object({
      file: text, location, symbol: nullableText, sink_or_string: nullableText,
    }) },
    detail: text,
  });
  const schema = {
    $schema: "http://json-schema.org/draft-07/schema#",
    title: "ExtRay portable candidate review v1",
    description: "Generated by npm run skill:sync. Structural validity is not claim verification.",
    ...object({
      schema_version: { const: "1.0" }, methodology: { const: "extray-review" },
      verification: { const: "not-run" },
      target: object({ name: text, version: text }),
      evidence_mode: enumOf(["source-only", "source-and-pack"]),
      investigation: enumOf(["complete", "incomplete"]),
      summary: text,
      findings: { type: "array", items: finding },
      coverage: { type: "array", minItems: DIMENSIONS.length, maxItems: DIMENSIONS.length,
        items: object({
          dimension: enumOf(DIMENSIONS), status: enumOf(["findings", "cleared", "inconclusive"]),
          finding_ids: { ...strings, uniqueItems: true }, checks_run: strings, note: text,
        }),
      },
      limitations: { ...strings, minItems: 1 },
    }),
  };
  const guidance = `# Shared investigation guidance

Generated by \`npm run skill:sync\` from ExtRay's Pi guidance. Edit
\`src/methodologies/pi/guidance.ts\` in the ExtRay repository and regenerate;
installed copies need no repository access.

These are ExtRay's investigation questions and classification conventions.
Use source evidence to support their application. The host's tools and the
portable report workflow are described in SKILL.md; Pi-specific tool names
below mean the equivalent source/evidence inspection in the host harness.

## Five dimensions

${DIMENSIONS.map((d) => `- **${d}**: ${DIMENSION_BRIEF[d]}`).join("\n")}

## Remote code classification

${REMOTE_CODE_RULES}

## Destination resolution

${HOST_RESOLUTION_RULE}
`;
  return { "investigation.md": guidance, "report.schema.json": JSON.stringify(schema, null, 2) + "\n" };
}

export function syncSkill(check: boolean): void {
  for (const [name, content] of Object.entries(skillAssets())) {
    const path = new URL(name, root);
    if (check) {
      if (readFileSync(path, "utf8") !== content) throw new Error(`Stale portable skill ${name}; run npm run skill:sync`);
    } else writeFileSync(path, content);
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    console.error("Usage: npm run skill:sync -- [--check]");
    process.exitCode = 2;
  } else {
    try {
      syncSkill(args[0] === "--check");
      console.log(args[0] === "--check" ? "Portable skill references are current." : "Updated portable skill references.");
    } catch (error) {
      console.error(error instanceof Error ? error.message : String(error));
      process.exitCode = 1;
    }
  }
}
